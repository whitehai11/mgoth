import {readFile} from 'node:fs/promises';
import {parseDocument} from 'yaml';
import assert from 'node:assert/strict';
const mainDoc=parseDocument(await readFile(new URL('../docker-compose.yml',import.meta.url),'utf8'),{uniqueKeys:true});
assert.equal(mainDoc.errors.length,0,mainDoc.errors.map(e=>e.message).join('\n'));
const compose=mainDoc.toJS();
const services=compose.services;
for(const name of ['web','admin','worker','transmission'])assert.ok(services[name],`Missing service: ${name}`);
for(const name of ['web','admin','worker','transmission'])assert.ok(services[name].healthcheck,`Missing healthcheck: ${name}`);
assert.deepEqual(services.web.ports,['127.0.0.1:8080:3000']);
assert.deepEqual(services.admin.ports,['127.0.0.1:3001:3001']);
assert.ok(!services.transmission.ports.some(port=>/9091/.test(port)),'Transmission RPC/Web UI must stay private');
assert.equal(services.web.depends_on.transmission.condition,'service_healthy');
assert.equal(services.worker.depends_on.web.condition,'service_healthy');
assert.equal(services.worker.depends_on.transmission.condition,'service_healthy');
const proxyDoc=parseDocument(await readFile(new URL('../deploy/docker-compose.proxy.yml',import.meta.url),'utf8'),{uniqueKeys:true});
assert.equal(proxyDoc.errors.length,0,proxyDoc.errors.map(e=>e.message).join('\n'));
const proxy=proxyDoc.toJS();
assert.ok(proxy.services.web.networks['reverse-proxy']);
assert.equal(proxy.networks['reverse-proxy'].external,true);
assert.ok(!proxy.services.admin,'The private admin service must not join the proxy overlay.');
console.log('Compose YAML and deployment invariants are valid. Run `docker compose config` on a host with Docker Compose to validate interpolation and the installed Compose version.');
